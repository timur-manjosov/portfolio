// Generates the Caddy configuration for timurmanjosov.com from
// deploy/site-config.json (headers + redirect table), so the local test
// server (tools/serve.mjs) and production cannot drift apart.
//
//   node tools/caddy-site-block.mjs example
//       → deploy/Caddyfile.example (site block only, for reading/review)
//
//   node tools/caddy-site-block.mjs propose <current Caddyfile> <output> [--web-root <dir>]
//       → full Caddyfile: the current file with ONLY the
//         `timurmanjosov.com, www.timurmanjosov.com` block replaced.
//         The site root is taken from the current block (`root * <dir>/current`),
//         so the server path never has to be in this repository; --web-root
//         overrides it (first deployment, or a move).
//         Fails unless
//           - everything before and after that block is byte-identical,
//           - every header of the old block is still sent and none got weaker,
//           - the new CSP is at least as strict as the old one,
//           - no directive of the old block is dropped (e.g. `log`).
//         Prints a short report; exit code 1 on any violation.
//
//   node tools/caddy-site-block.mjs smoke-data <dir>
//       → redirects.tsv, expected-headers.tsv, language-door.tsv for the
//         smoke tests in deploy/apply-on-server.sh (no Node on the server).
import { readFileSync, writeFileSync } from "node:fs";

const config = JSON.parse(readFileSync(new URL("../deploy/site-config.json", import.meta.url), "utf8"));
/** Placeholder for the review copy only; `propose` uses the live root. */
const EXAMPLE_ROOT = "/srv/www/timurmanjosov.com/current";
const door = config.languageDoor;
/** [Accept-Language value or "-" for none, expected Location]; site-config.json. */
const DOOR_CASES = door.tests;
// The JS reading of the regex (tools/serve.mjs) must agree with the test
// table; the Caddy side is checked on the server (apply-on-server.sh).
for (const [al, to] of DOOR_CASES) {
  const got = al !== "-" && new RegExp(door.acceptLanguage, "i").test(al) ? door.match : door.default;
  if (got !== to) throw new Error(`languageDoor: "${al}" → ${got}, test table expects ${to}`);
}
const BLOCK_HEADER = /^timurmanjosov\.com,\s*www\.timurmanjosov\.com\s*\{/m;
const MARK_BEGIN =
  "# BEGIN timurmanjosov.com, generated by tools/caddy-site-block.mjs from deploy/site-config.json";
const MARK_END = "# END timurmanjosov.com";

const quote = (v) => `"${v.replace(/"/g, '\\"')}"`;

function headerBlock(indent) {
  const lines = Object.entries(config.headers).map(([k, v]) => `${indent}\t${k} ${quote(v)}`);
  // Do not advertise the server software (stricter than before, never looser).
  lines.push(`${indent}\t-Server`);
  return `${indent}header {\n${lines.join("\n")}\n${indent}}`;
}

export function siteBlock(root = EXAMPLE_ROOT) {
  if (!/^\/[A-Za-z0-9._/-]+\/current$/.test(root)) throw new Error(`unexpected site root: ${root}`);
  const redirects = config.redirects.map((r) => `\tredir ${r.from} ${r.to} ${r.status}`).join("\n");
  const re = quote(`(?i)${door.acceptLanguage}`);
  return `${MARK_BEGIN}
# Canonical host: www redirects to the apex (before: both served the same
# content, i.e. duplicate URLs).
www.timurmanjosov.com {
	redir https://timurmanjosov.com{uri} 308
}

timurmanjosov.com {
	# Release directory; deploy/apply-on-server.sh flips this symlink.
	root * ${root}
	encode zstd gzip

	# Security headers. Strict CSP without 'unsafe-inline' and, unlike the
	# previous config, without a script hash: the theme-init script is an
	# external file now (docs/adr/0001-stack.md).
${headerBlock("\t")}

	# Caching. Astro puts every CSS/JS/font file under /_astro/ with a content
	# hash in its name, so those can be cached forever. Everything else is
	# revalidated (file_server sends ETag/Last-Modified), except the language
	# door below, which must never be cached.
	@hashed path /_astro/*
	header @hashed Cache-Control "public, max-age=31536000, immutable"
	@unhashed not path /_astro/* ${door.path}
	header @unhashed Cache-Control "public, max-age=0, must-revalidate"

	# Language door: ${door.path} answers ${door.status} by the FIRST Accept-Language
	# entry (browsers sort by preference): ${door.match} if it matches, else
	# ${door.default} (also for "*" and a missing header). Only ${door.path} does this;
	# every /de/… and /en/… URL is served as is. The response depends on a
	# request header, so it carries Vary and is never cached.
	@door path ${door.path}
	header @door {
		Cache-Control "no-store"
		Vary "Accept-Language"
	}
	@door_match {
		path ${door.path}
		header_regexp Accept-Language ${re}
	}
	@door_default {
		path ${door.path}
		not header_regexp Accept-Language ${re}
	}
	redir @door_match ${door.match} ${door.status}
	redir @door_default ${door.default} ${door.status}

	# Web Key Directory for the OpenPGP key (only relevant once a key is
	# published under /.well-known/openpgpkey/, see docs/DEPLOY.md).
	@wkd path /.well-known/openpgpkey/*
	header @wkd Access-Control-Allow-Origin "*"

	# Old URLs → new URLs (redirect table: deploy/site-config.json,
	# documented in docs/DEPLOY.md). 301 = permanent move, 302 = convenience
	# path whose language target may change later.
${redirects}

	file_server

	# Helpful 404 pages, per language; the status stays 404.
	handle_errors 404 {
${headerBlock("\t\t")}
		header Cache-Control "no-store"
		@de path /de/*
		rewrite @de /de/404/index.html
		@en path /en/*
		rewrite @en /en/404/index.html
		@other not path /de/* /en/*
		rewrite @other /404.html
		file_server
	}
}
${MARK_END}`;
}

/** Index range [start, end) of the top-level block whose header matches `re`. */
function findBlock(text, re) {
  const m = re.exec(text);
  if (!m) return null;
  let depth = 0;
  let inQuote = false;
  let inComment = false;
  for (let i = m.index; i < text.length; i++) {
    const c = text[i];
    if (inComment) {
      if (c === "\n") inComment = false;
      continue;
    }
    if (inQuote) {
      if (c === "\\") i++;
      else if (c === '"') inQuote = false;
      continue;
    }
    if (c === "#" && (i === 0 || /\s/.test(text[i - 1]))) inComment = true;
    else if (c === '"') inQuote = true;
    else if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return [m.index, i + 1];
    }
  }
  throw new Error("Unbalanced braces in the timurmanjosov.com block");
}

function parseCsp(value) {
  return Object.fromEntries(
    value
      .split(";")
      .map((d) => d.trim().split(/\s+/))
      .filter((d) => d[0])
      .map(([name, ...sources]) => [name.toLowerCase(), new Set(sources)]),
  );
}

/** Headers set in a block: `header { Name value }` and `header Name value`. */
function headersOf(block) {
  const out = {};
  const add = (name, value) => {
    out[name.toLowerCase()] = value.replace(/^"|"$/g, "").replace(/\\"/g, '"');
  };
  for (const m of block.matchAll(/^\s*header\s*\{([\s\S]*?)^\s*\}/gm)) {
    for (const line of m[1].split("\n")) {
      const kv = line.trim().match(/^([A-Za-z][\w-]*)\s+(.+)$/);
      if (kv) add(kv[1], kv[2]);
    }
  }
  for (const m of block.matchAll(/^\s*header\s+([A-Za-z][\w-]*)\s+("[^"]*"|\S+)\s*$/gm)) add(m[1], m[2]);
  return out;
}

/** First word of every line directly inside a site block (depth 1): directives and matchers. */
function topLevelDirectives(block) {
  const names = new Set();
  let depth = 0;
  for (const raw of block.split("\n")) {
    const line = raw.replace(/(^|\s)#.*$/, "").trim();
    if (depth === 1 && line && !line.startsWith("}")) {
      const word = line.split(/\s+/)[0];
      names.add(word.startsWith("@") ? "@matcher" : word);
    }
    for (const c of line.replace(/"[^"]*"/g, "")) {
      if (c === "{") depth++;
      else if (c === "}") depth--;
    }
  }
  return names;
}

function compareSecurity(oldBlock, newBlock, problems, notes) {
  // A directive in the old block that the generated one lacks (e.g. `log`,
  // `tls`, `basic_auth`) would silently disappear: refuse instead.
  const newDirectives = topLevelDirectives(newBlock);
  for (const d of topLevelDirectives(oldBlock)) {
    if (!newDirectives.has(d)) problems.push(`directive \`${d}\` of the old block is missing in the new one`);
  }

  const before = headersOf(oldBlock);
  const after = headersOf(newBlock);
  for (const [name, value] of Object.entries(before)) {
    if (name === "cache-control") continue; // caching policy, not security
    if (!(name in after)) {
      problems.push(`header ${name} is no longer sent`);
      continue;
    }
    if (name === "content-security-policy") {
      const o = parseCsp(value);
      const n = parseCsp(after[name]);
      for (const directive of Object.keys(o)) {
        if (!n[directive]) problems.push(`CSP directive ${directive} was removed`);
      }
      for (const [directive, sources] of Object.entries(n)) {
        const allowed = o[directive] ?? o["default-src"] ?? new Set();
        for (const s of sources) {
          if (!allowed.has(s)) problems.push(`CSP ${directive} gains source ${s} (looser)`);
        }
        for (const s of allowed) {
          if (!sources.has(s)) notes.push(`CSP ${directive}: drops ${s} (stricter)`);
        }
      }
    } else if (name === "strict-transport-security") {
      const age = (v) => Number(v.match(/max-age=(\d+)/)?.[1] ?? 0);
      if (age(after[name]) < age(value)) problems.push("HSTS max-age got shorter");
      if (/includesubdomains/i.test(value) && !/includesubdomains/i.test(after[name])) {
        problems.push("HSTS lost includeSubDomains");
      }
      if (/preload/i.test(value) && !/preload/i.test(after[name])) problems.push("HSTS lost preload");
    } else if (after[name] !== value) {
      problems.push(`header ${name} changed: ${value} → ${after[name]} (review whether that is stricter)`);
    }
  }
  for (const name of Object.keys(after)) {
    if (!(name in before) && name !== "cache-control") notes.push(`new header: ${name}`);
  }
}

const [mode, input, output, ...rest] = process.argv.slice(2);
const webRootArg = rest[0] === "--web-root" ? rest[1] : null;
if (rest.length && !webRootArg) throw new Error(`unknown arguments: ${rest.join(" ")}`);

if (mode === "example") {
  const text = `# timurmanjosov.com, Caddy site block (example / review copy).
# Generated by tools/caddy-site-block.mjs from deploy/site-config.json.
# The live server config is /etc/caddy/Caddyfile; deploy/stage.sh builds a
# full proposal from it (only this block is replaced), see docs/DEPLOY.md.

${siteBlock()}
`;
  writeFileSync("deploy/Caddyfile.example", text);
  console.log("wrote deploy/Caddyfile.example");
} else if (mode === "propose") {
  if (!input || !output) throw new Error("usage: propose <current Caddyfile> <output>");
  const current = readFileSync(input, "utf8");
  // A previous run of this script leaves BEGIN/END markers; replace between them.
  let start;
  let end;
  const begin = current.indexOf(MARK_BEGIN);
  if (begin !== -1) {
    start = begin;
    end = current.indexOf(MARK_END, begin) + MARK_END.length;
  } else {
    const range = findBlock(current, BLOCK_HEADER);
    if (!range) throw new Error("block `timurmanjosov.com, www.timurmanjosov.com {` not found");
    [start, end] = range;
  }
  const oldBlock = current.slice(start, end);
  // The root comes from the live block (never from this repository).
  const liveRoot = oldBlock.match(/^\s*root\s+\*\s+(\S+)\s*$/m)?.[1];
  const root = webRootArg ? `${webRootArg.replace(/\/+$/, "")}/current` : liveRoot;
  if (!root) throw new Error("no `root *` in the current block; pass --web-root <dir>");
  if (!root.endsWith("/current"))
    throw new Error(`root ${root} does not end in /current; pass --web-root <dir>`);
  const newBlock = siteBlock(root);
  const proposed = current.slice(0, start) + newBlock + current.slice(end);

  const problems = [];
  const notes = [];
  // Byte identity of everything outside the block (Aura etc.).
  const prefixOk = proposed.slice(0, start) === current.slice(0, start);
  const suffixOk = proposed.slice(start + newBlock.length) === current.slice(end);
  if (!prefixOk || !suffixOk) problems.push("content outside the site block changed");
  compareSecurity(oldBlock, newBlock, problems, notes);

  writeFileSync(output, proposed);
  console.log(`proposal: ${output}`);
  console.log(`replaced bytes ${start}..${end} of ${current.length} (site block only)`);
  console.log(`outside the block: ${prefixOk && suffixOk ? "byte-identical" : "CHANGED"}`);
  for (const n of notes) console.log(`  note: ${n}`);
  if (problems.length) {
    console.error("✗ proposal rejected:");
    for (const p of problems) console.error(`  - ${p}`);
    process.exitCode = 1;
  } else {
    console.log("✓ proposal: no security header got weaker, rest of file untouched");
  }
} else if (mode === "smoke-data") {
  // Plain-text inputs for deploy/apply-on-server.sh, which runs on a host
  // without Node or jq: one redirect / one expected header per line.
  if (!input) throw new Error("usage: smoke-data <dir>");
  writeFileSync(
    `${input}/redirects.tsv`,
    `${config.redirects.map((r) => `${r.from}\t${r.to}\t${r.status}`).join("\n")}\n`,
  );
  writeFileSync(
    `${input}/expected-headers.tsv`,
    `${Object.entries(config.headers)
      .map(([k, v]) => `${k}\t${v}`)
      .join("\n")}\n`,
  );
  // Accept-Language value → expected Location of the language door
  // (the same table tools/check-http.mjs tests locally). "-" = no header.
  writeFileSync(`${input}/language-door.tsv`, `${DOOR_CASES.map(([al, to]) => `${al}\t${to}`).join("\n")}\n`);
  console.log(`wrote redirects.tsv, expected-headers.tsv and language-door.tsv to ${input}`);
} else {
  console.error("usage: caddy-site-block.mjs example | propose <current> <output> | smoke-data <dir>");
  process.exitCode = 2;
}
